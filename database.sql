
-- ==========================================
-- DATABASE RESERVASI KOST - POSTGRESQL
-- ==========================================

-- TABEL USERS
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100),
    email VARCHAR(100) UNIQUE,
    hp VARCHAR(20),
    password VARCHAR(255),
    role VARCHAR(10) DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- TABEL KAMAR
CREATE TABLE kamar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100),
    tipe VARCHAR(10)
        CHECK (tipe IN ('Putra', 'Putri', 'Campur')),
    harga INTEGER,
    luas VARCHAR(20),
    fasilitas VARCHAR(255),
    deskripsi TEXT,
    emoji VARCHAR(10) DEFAULT '🏠',
    status VARCHAR(10) DEFAULT 'tersedia'
        CHECK (status IN ('tersedia', 'terisi'))
);

-- TABEL RESERVASI
CREATE TABLE reservasi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    kamar_id INTEGER REFERENCES kamar(id) ON DELETE CASCADE,
    tgl_masuk DATE,
    durasi INTEGER,
    total INTEGER,
    catatan TEXT,
    status VARCHAR(20) DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'dikonfirmasi',
            'ditolak',
            'dibatalkan'
        )),
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- TABEL PESAN
CREATE TABLE pesan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100),
    email VARCHAR(100),
    isi TEXT,
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

